    #[test]
    fn coefficient_subgroup_binding_replays_backend_bytes_and_rejects_layout_mutations() {
        let code = coefficient_code();
        let whir = whir();
        let root = core::array::from_fn(|index| F::from_usize(100 + index));
        let descriptor = TerminalDescriptor::from_whir_initial_rs(root, &code, &whir, D_EF);
        let binding =
            NativeTerminalTranscriptBinding::coefficient_subgroup(&descriptor, &code, &whir)
                .expect("exact coefficient terminal binding");
        assert_eq!(binding.layout(), WhirInitialRsLayout::CoefficientSubgroup);
        assert!(binding
            .whir_layout()
            .windows(COEFFICIENT_SUBGROUP_RS_LAYOUT_TAG.len())
            .any(|window| {
                window.iter().copied().eq(COEFFICIENT_SUBGROUP_RS_LAYOUT_TAG
                    .iter()
                    .copied()
                    .map(F::from_u8))
            }));
        let metadata_word_image = descriptor
            .metadata_words()
            .map(F::from_u64)
            .collect::<Vec<_>>();
        assert_ne!(binding.descriptor_post_root(), metadata_word_image);

        let mut changed = descriptor.clone();
        changed.code_layout_version ^= 1;
        assert_eq!(
            NativeTerminalTranscriptBinding::coefficient_subgroup(&changed, &code, &whir),
            Err(NativeTerminalTranscriptBindingError::Descriptor),
        );
        let mut changed = descriptor.clone();
        changed.initial_folding_factor = 1;
        assert_eq!(
            NativeTerminalTranscriptBinding::coefficient_subgroup(&changed, &code, &whir),
            Err(NativeTerminalTranscriptBindingError::Descriptor),
        );
        let config =
            SC::default_from_params(openvm_stark_backend::SystemParams::new_for_testing(8));
        let ordinary = WhirInitialRsWarpCode::new(config.hasher().clone(), 8, 1, 0, 16);
        assert_eq!(
            NativeTerminalTranscriptBinding::coefficient_subgroup(&descriptor, &ordinary, &whir,),
            Err(NativeTerminalTranscriptBindingError::Layout),
        );

        // The root is dynamic and therefore deliberately excluded from the
        // setup-fixed tail; it is constrained separately by the root bus.
        let mut changed_root = descriptor;
        changed_root.root[0] += F::ONE;
        let changed_binding =
            NativeTerminalTranscriptBinding::coefficient_subgroup(&changed_root, &code, &whir)
                .expect("dynamic root uses the same setup-fixed tail");
        assert_eq!(binding, changed_binding);
    }

    #[test]
    fn reduced_swirl_terminal_accepts_only_the_exact_eq_claim() {
        let point = vec![EF::from_u64(3), EF::from_u64(5), EF::from_u64(7)];
        let source_target = EF::from_u64(11);
        let eta = EF::from_u64(13);
        let beta = point
            .iter()
            .copied()
            .chain([source_target])
            .collect::<Vec<_>>();
        let statement = TerminalConstrainedRsStatement {
            linearizer_claims: vec![TerminalStructuredLinearClaim::new(
                TerminalWeightSpec::Eq {
                    point: point.clone(),
                },
                source_target + eta,
            )],
        };
        assert_eq!(
            validate_native_terminal_eq_statement(&beta, eta, &statement),
            Ok(NativeTerminalEqClaim {
                point: point.clone(),
                target: source_target + eta,
            }),
        );

        let mut wrong_coordinate = statement.clone();
        if let TerminalWeightSpec::Eq { point } = &mut wrong_coordinate.linearizer_claims[0].weight
        {
            point[1] += EF::ONE;
        } else {
            unreachable!()
        }
        assert_eq!(
            validate_native_terminal_eq_statement(&beta, eta, &wrong_coordinate),
            Err(NativeTerminalEqClaimError::Relation),
        );
        let mut wrong_target = statement.clone();
        wrong_target.linearizer_claims[0].target += EF::ONE;
        assert_eq!(
            validate_native_terminal_eq_statement(&beta, eta, &wrong_target),
            Err(NativeTerminalEqClaimError::Relation),
        );
        let mapped = TerminalConstrainedRsStatement {
            linearizer_claims: vec![TerminalStructuredLinearClaim::new(
                TerminalWeightSpec::PrismalinearMappedColumns(PrismalinearMappedColumnWeight {
                    log_message_len: beta.len() - 1,
                    terms: Vec::new(),
                }),
                source_target + eta,
            )],
        };
        assert_eq!(
            validate_native_terminal_eq_statement(&beta, eta, &mapped),
            Err(NativeTerminalEqClaimError::Relation),
        );
    }

    #[test]
    fn coefficient_eq_pullback_matches_backend_coordinates() {
        let code = coefficient_code();
        let point = (0..code.log_message_len())
            .map(|index| EF::from_usize(17 + 3 * index))
            .collect::<Vec<_>>();
        let whir_point = (0..code.log_message_len())
            .map(|index| EF::from_usize(43 + 5 * index))
            .collect::<Vec<_>>();
        let xi = EF::from_u64(97);
        let statement = TerminalConstrainedRsStatement {
            linearizer_claims: vec![TerminalStructuredLinearClaim::new(
                TerminalWeightSpec::Eq {
                    point: point.clone(),
                },
                EF::from_u64(101),
            )],
        };
        let backend = statement.batched_linearizer_weight_eval_at(&code, xi, &whir_point);
        let recursive = xi
            * point
                .iter()
                .rev()
                .zip(&whir_point)
                .map(|(&beta, &coordinate)| {
                    EF::ONE - coordinate - beta.double() + EF::from_u64(3) * coordinate * beta
                })
                .product::<EF>();
        assert_eq!(recursive, backend);

        let mut changed = point;
        changed[0] += EF::ONE;
        let changed_statement = TerminalConstrainedRsStatement {
            linearizer_claims: vec![TerminalStructuredLinearClaim::new(
                TerminalWeightSpec::Eq { point: changed },
                EF::from_u64(101),
            )],
        };
        assert_ne!(
            changed_statement.batched_linearizer_weight_eval_at(&code, xi, &whir_point),
            backend,
        );
    }

