pub const NATIVE_TERMINAL_DESCRIPTOR_DOMAIN_TAG: u64 = 917_001;

/// Setup-fixed observations between the dynamic terminal root and the first
/// terminal-WHIR challenge.
///
/// The values are generated by the backend's own
/// [`TerminalDescriptor::observe_fiat_shamir`] and
/// [`observe_terminal_whir_layout_binding`] implementations.  In particular,
/// coefficient-native layouts retain both byte encodings; callers cannot
/// substitute `TerminalDescriptor::metadata_words()`, whose field-word image
/// is not the Fiat--Shamir byte image.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NativeTerminalTranscriptBinding {
    layout: WhirInitialRsLayout,
    descriptor_post_root: Arc<[F]>,
    whir_layout: Arc<[F]>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum NativeTerminalTranscriptBindingError {
    Descriptor,
    Layout,
    Transcript,
}

impl NativeTerminalTranscriptBinding {
    /// Construct the exact binding used by the coefficient-native SWIRL
    /// terminal. Ordinary-subgroup layouts are rejected: this module
    /// certifies the reduced-SWIRL Eq relation and accepts only the
    /// coefficient-subgroup layout.
    pub fn coefficient_subgroup<Obs>(
        descriptor: &TerminalDescriptor<Digest>,
        code: &WhirInitialRsWarpCode<<SC as StarkProtocolConfig>::Hasher, Obs>,
        whir: &WhirConfig,
    ) -> Result<Self, NativeTerminalTranscriptBindingError> {
        if code.layout() != WhirInitialRsLayout::CoefficientSubgroup {
            return Err(NativeTerminalTranscriptBindingError::Layout);
        }
        descriptor
            .validate_whir_initial_rs::<<SC as StarkProtocolConfig>::Hasher, Obs>(
                &descriptor.root,
                code,
                whir,
                D_EF,
            )
            .map_err(|_| NativeTerminalTranscriptBindingError::Descriptor)?;

        let mut challenger = NativeWarpChallenger::<SC, _>::new(default_duplex_sponge_recorder());
        descriptor.observe_fiat_shamir::<SC, _>(&mut challenger);
        let descriptor_end = challenger
            .history_checkpoint()
            .ok_or(NativeTerminalTranscriptBindingError::Transcript)?;
        observe_terminal_whir_layout_binding::<SC, Obs, _>(code, &mut challenger)
            .map_err(|_| NativeTerminalTranscriptBindingError::Layout)?;
        let transcript_end = challenger
            .history_checkpoint()
            .ok_or(NativeTerminalTranscriptBindingError::Transcript)?;
        let log = TranscriptHistory::into_log(challenger.into_inner());

        let root_end = 1usize
            .checked_add(DIGEST_SIZE)
            .ok_or(NativeTerminalTranscriptBindingError::Transcript)?;
        if descriptor_end.operations < root_end
            || transcript_end.operations < descriptor_end.operations
            || log.values().len() != transcript_end.operations
            || log.samples().iter().any(|&sample| sample)
            || log.values().first() != Some(&F::from_u64(NATIVE_TERMINAL_DESCRIPTOR_DOMAIN_TAG))
            || log.values().get(1..root_end) != Some(descriptor.root.as_slice())
        {
            return Err(NativeTerminalTranscriptBindingError::Transcript);
        }
        let descriptor_post_root = log
            .values()
            .get(root_end..descriptor_end.operations)
            .ok_or(NativeTerminalTranscriptBindingError::Transcript)?
            .to_vec();
        let whir_layout = log
            .values()
            .get(descriptor_end.operations..transcript_end.operations)
            .ok_or(NativeTerminalTranscriptBindingError::Transcript)?
            .to_vec();
        if whir_layout.is_empty() {
            return Err(NativeTerminalTranscriptBindingError::Layout);
        }
        Ok(Self {
            layout: code.layout(),
            descriptor_post_root: descriptor_post_root.into(),
            whir_layout: whir_layout.into(),
        })
    }

    #[must_use]
    pub const fn layout(&self) -> WhirInitialRsLayout {
        self.layout
    }

    pub fn descriptor_post_root(&self) -> &[F] {
        &self.descriptor_post_root
    }

    pub fn whir_layout(&self) -> &[F] {
        &self.whir_layout
    }

    #[must_use]
    pub fn whir_post_root_len(&self) -> usize {
        self.descriptor_post_root.len() + self.whir_layout.len()
    }

    fn whir_post_root(&self) -> impl Iterator<Item = F> + '_ {
        self.descriptor_post_root
            .iter()
            .chain(self.whir_layout.iter())
            .copied()
    }
}

/// The sole nonlinear terminal claim for reduced SWIRL WARP is
/// `P(beta, message) = target`, represented by one Eq weight.  The last
/// normalized beta coordinate stores the source target and WARP's accumulated
/// residual is added back exactly as required by the reduced-code adapter.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NativeTerminalEqClaim {
    pub point: Vec<EF>,
    pub target: EF,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum NativeTerminalEqClaimError {
    Shape,
    Relation,
}

pub fn native_terminal_eq_claim(
    normalized_beta: &[EF],
    accumulated_eta: EF,
) -> Result<NativeTerminalEqClaim, NativeTerminalEqClaimError> {
    let (&source_target, point) = normalized_beta
        .split_last()
        .ok_or(NativeTerminalEqClaimError::Shape)?;
    if point.is_empty() {
        return Err(NativeTerminalEqClaimError::Shape);
    }
    Ok(NativeTerminalEqClaim {
        point: point.to_vec(),
        target: source_target + accumulated_eta,
    })
}

pub fn validate_native_terminal_eq_statement(
    normalized_beta: &[EF],
    accumulated_eta: EF,
    statement: &TerminalConstrainedRsStatement<EF>,
) -> Result<NativeTerminalEqClaim, NativeTerminalEqClaimError> {
    let expected = native_terminal_eq_claim(normalized_beta, accumulated_eta)?;
    let [claim] = statement.linearizer_claims.as_slice() else {
        return Err(NativeTerminalEqClaimError::Relation);
    };
    match &claim.weight {
        TerminalWeightSpec::Eq { point }
            if point == &expected.point && claim.target == expected.target =>
        {
            Ok(expected)
        }
        TerminalWeightSpec::Eq { .. } | TerminalWeightSpec::PrismalinearMappedColumns(_) => {
            Err(NativeTerminalEqClaimError::Relation)
        }
    }
}

#[repr(C)]
#[derive(AlignedBorrow, StructReflection)]
pub struct NativeTerminalWhirStatementCols<T> {
    pub active: T,
    pub tidx: T,
    pub root: [T; DIGEST_SIZE],
    pub mu: [T; D_EF],
    pub beta_last: [T; D_EF],
    pub eta: [T; D_EF],
    pub batching_challenge: [T; D_EF],
    pub initial_claim: [T; D_EF],
}

/// Replays the base-field terminal descriptor, samples `xi`, and constructs
/// `mu + xi * (eta + beta_last)`.
#[derive(ColumnsAir)]
#[columns_via(NativeTerminalWhirStatementCols<u8>)]
pub struct NativeTerminalWhirStatementAir {
    pub transcript_bus: TranscriptBus,
    pub linearizer_end_bus: NativeTerminalLinearizerEndBus,
    pub statement_bus: NativeTerminalWhirStatementBus,
    pub transcript_binding: Arc<NativeTerminalTranscriptBinding>,
}

impl BaseAirWithPublicValues<F> for NativeTerminalWhirStatementAir {}
impl PartitionedBaseAir<F> for NativeTerminalWhirStatementAir {}
impl BaseAir<F> for NativeTerminalWhirStatementAir {
    fn width(&self) -> usize {
        NativeTerminalWhirStatementCols::<F>::width()
    }
}

impl<AB: AirBuilder<F = F> + InteractionBuilder> Air<AB> for NativeTerminalWhirStatementAir
where
    <AB::Expr as PrimeCharacteristicRing>::PrimeSubfield: BinomiallyExtendable<{ D_EF }>,
{
    fn eval(&self, builder: &mut AB) {
        let main = builder.main();
        let row = main
            .row_slice(0)
            .expect("native terminal WHIR statement row");
        let local: &NativeTerminalWhirStatementCols<AB::Var> = (*row).borrow();
        builder.assert_bool(local.active);
        builder.when_first_row().assert_one(local.active);
        builder.when_transition().assert_zero(local.active);

        self.linearizer_end_bus.receive(
            builder,
            NativeTerminalLinearizerEndMessage {
                tidx: local.tidx.into(),
                root: local.root.map(Into::into),
                mu: local.mu.map(Into::into),
                beta_last: local.beta_last.map(Into::into),
                eta: local.eta.map(Into::into),
            },
            local.active,
        );
        self.transcript_bus.observe(
            builder,
            AB::Expr::ZERO,
            local.tidx.into(),
            AB::Expr::from_u64(NATIVE_TERMINAL_DESCRIPTOR_DOMAIN_TAG),
            local.active,
        );
        self.transcript_bus.observe_commit(
            builder,
            AB::Expr::ZERO,
            AB::Expr::from(local.tidx) + AB::Expr::ONE,
            local.root,
            local.active,
        );
        let metadata_tidx = AB::Expr::from(local.tidx) + AB::Expr::from_usize(1 + DIGEST_SIZE);
        for (index, value) in self.transcript_binding.whir_post_root().enumerate() {
            self.transcript_bus.observe(
                builder,
                AB::Expr::ZERO,
                metadata_tidx.clone() + AB::Expr::from_usize(index),
                AB::Expr::from(value),
                local.active,
            );
        }
        let batching_tidx =
            metadata_tidx + AB::Expr::from_usize(self.transcript_binding.whir_post_root_len());
        self.transcript_bus.sample_ext(
            builder,
            AB::Expr::ZERO,
            batching_tidx.clone(),
            local.batching_challenge,
            local.active,
        );
        let target = core::array::from_fn(|limb| {
            AB::Expr::from(local.eta[limb]) + AB::Expr::from(local.beta_last[limb])
        });
        assert_array_eq(&mut builder.when(local.active), local.initial_claim, {
            let product = ext_field_multiply::<AB::Expr>(local.batching_challenge, target);
            core::array::from_fn(|limb| AB::Expr::from(local.mu[limb]) + product[limb].clone())
        });
        self.statement_bus.add_key_with_lookups(
            builder,
            NativeTerminalWhirStatementMessage {
                tidx: batching_tidx + AB::Expr::from_usize(D_EF),
                root: local.root.map(Into::into),
                batching_challenge: local.batching_challenge.map(Into::into),
                initial_claim: local.initial_claim.map(Into::into),
            },
            local.active * AB::Expr::TWO,
        );
    }
}

