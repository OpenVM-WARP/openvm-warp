impl<AB: AirBuilder<F = F> + InteractionBuilder> Air<AB> for NativeTerminalWhirLinearizerWeightAir
where
    <AB::Expr as PrimeCharacteristicRing>::PrimeSubfield: BinomiallyExtendable<{ D_EF }>,
{
    fn eval(&self, builder: &mut AB) {
        let main = builder.main();
        let local_row = main
            .row_slice(0)
            .expect("native terminal linearizer weight row");
        let next_row = main
            .row_slice(1)
            .expect("native terminal next linearizer weight row");
        let local: &NativeTerminalWhirLinearizerWeightCols<AB::Var> = (*local_row).borrow();
        let next: &NativeTerminalWhirLinearizerWeightCols<AB::Var> = (*next_row).borrow();

        for flag in [local.active, local.is_first, local.is_last] {
            builder.assert_bool(flag);
        }
        builder.when_first_row().assert_one(local.active);
        builder.when_first_row().assert_one(local.is_first);
        builder.when_first_row().assert_zero(local.coordinate);
        builder.when(local.active * local.is_last).assert_eq(
            local.coordinate,
            AB::Expr::from_usize(self.log_message_len - 1),
        );
        builder
            .when_transition()
            .assert_bool(local.active - next.active);
        builder
            .when_transition()
            .assert_eq(local.active - next.active, local.is_last);
        let mut transition = builder.when_transition();
        let mut same = transition.when(next.active);
        same.assert_zero(next.is_first);
        same.assert_eq(next.coordinate, local.coordinate + AB::F::ONE);
        same.assert_eq(next.statement_tidx, local.statement_tidx);
        assert_array_eq(&mut same, next.root, local.root);
        assert_array_eq(&mut same, next.batching_challenge, local.batching_challenge);
        assert_array_eq(&mut same, next.initial_claim, local.initial_claim);
        assert_array_eq(&mut same, next.product_before, local.product_after);
        builder
            .when_last_row()
            .assert_eq(local.is_last, local.active);

        self.statement_bus.lookup_key(
            builder,
            NativeTerminalWhirStatementMessage {
                tidx: local.statement_tidx.into(),
                root: local.root.map(Into::into),
                batching_challenge: local.batching_challenge.map(Into::into),
                initial_claim: local.initial_claim.map(Into::into),
            },
            local.active * local.is_first,
        );
        self.accumulator_value_bus.lookup_key(
            builder,
            NativeTerminalAccumulatorValueMessage {
                section: AB::Expr::from_usize(2),
                coordinate: AB::Expr::from_usize(self.log_message_len - 1) - local.coordinate,
                value: local.beta.map(Into::into),
            },
            local.active,
        );
        self.point_bus.lookup_key(
            builder,
            NativeTerminalWhirPointMessage {
                coordinate: local.coordinate.into(),
                value: local.point.map(Into::into),
            },
            local.active,
        );
        let one = core::array::from_fn(|limb| {
            if limb == 0 {
                AB::Expr::ONE
            } else {
                AB::Expr::ZERO
            }
        });
        assert_array_eq(
            &mut builder.when(local.active * local.is_first),
            local.product_before,
            one.clone(),
        );
        let point_beta = ext_field_multiply::<AB::Expr>(local.point, local.beta);
        let expected_factor = core::array::from_fn(|limb| {
            one[limb].clone()
                - AB::Expr::from(local.point[limb])
                - AB::Expr::TWO * AB::Expr::from(local.beta[limb])
                + AB::Expr::from_usize(3) * point_beta[limb].clone()
        });
        assert_array_eq(
            &mut builder.when(local.active),
            local.factor,
            expected_factor,
        );
        assert_array_eq(
            &mut builder.when(local.active),
            local.product_after,
            ext_field_multiply::<AB::Expr>(local.product_before, local.factor),
        );
        self.output_bus.send(
            builder,
            NativeTerminalWhirLinearizerWeightMessage {
                value: ext_field_multiply::<AB::Expr>(
                    local.batching_challenge,
                    local.product_after,
                ),
            },
            local.active * local.is_last,
        );
    }
}

pub fn generate_native_terminal_whir_statement_trace(
    descriptor: &TerminalDescriptor<Digest>,
    transcript_binding: &NativeTerminalTranscriptBinding,
    mu: EF,
    beta_last: EF,
    eta: EF,
    verification: &TerminalWhirVerification<F, EF, Digest>,
    transcript: &TranscriptLog<F, [F; 16]>,
) -> Option<RowMajorMatrix<F>> {
    if transcript_binding.layout() != WhirInitialRsLayout::CoefficientSubgroup
        || verification.root != descriptor.root
        || verification.initial_claim != mu + verification.batching_challenge * (eta + beta_last)
    {
        return None;
    }
    let tidx = verification.transcript_start.operations;
    let metadata_len = transcript_binding.whir_post_root_len();
    let batching_tidx = tidx.checked_add(1 + DIGEST_SIZE + metadata_len)?;
    if verification.descriptor_span.start.operations != tidx
        || verification.descriptor_span.end.operations != batching_tidx
        || verification.batching_challenge_span.start.operations != batching_tidx
        || verification.batching_challenge_span.end.operations != batching_tidx + D_EF
        || transcript.values().get(tidx)? != &F::from_u64(NATIVE_TERMINAL_DESCRIPTOR_DOMAIN_TAG)
    {
        return None;
    }
    let root_start = tidx.checked_add(1)?;
    let root_end = root_start.checked_add(DIGEST_SIZE)?;
    if transcript.values().get(root_start..root_end)? != descriptor.root.as_slice()
        || transcript
            .samples()
            .get(tidx..batching_tidx)?
            .iter()
            .any(|&sample| sample)
        || transcript
            .values()
            .get(root_end..batching_tidx)?
            .iter()
            .copied()
            .ne(transcript_binding.whir_post_root())
        || transcript
            .values()
            .get(batching_tidx..batching_tidx + D_EF)?
            != verification
                .batching_challenge
                .as_basis_coefficients_slice()
        || transcript
            .samples()
            .get(batching_tidx..batching_tidx + D_EF)?
            .iter()
            .any(|&sample| !sample)
    {
        return None;
    }
    let width = NativeTerminalWhirStatementCols::<F>::width();
    let mut values = F::zero_vec(width);
    let cols: &mut NativeTerminalWhirStatementCols<F> = values.as_mut_slice().borrow_mut();
    cols.active = F::ONE;
    cols.tidx = F::from_usize(tidx);
    cols.root = descriptor.root;
    copy_ext(&mut cols.mu, mu);
    copy_ext(&mut cols.beta_last, beta_last);
    copy_ext(&mut cols.eta, eta);
    copy_ext(
        &mut cols.batching_challenge,
        verification.batching_challenge,
    );
    copy_ext(&mut cols.initial_claim, verification.initial_claim);
    Some(RowMajorMatrix::new(values, width))
}

pub fn generate_native_terminal_whir_linearizer_weight_trace(
    beta: &[EF],
    verification: &TerminalWhirVerification<F, EF, Digest>,
    required_height: Option<usize>,
) -> Option<RowMajorMatrix<F>> {
    let log_message_len = beta.len().checked_sub(1)?;
    let mut point = verification
        .rounds
        .iter()
        .flat_map(|round| round.alphas.iter().copied())
        .collect::<Vec<_>>();
    point.extend_from_slice(&verification.suffix_point);
    if point.len() != log_message_len || log_message_len == 0 {
        return None;
    }
    let height = required_height.unwrap_or_else(|| log_message_len.next_power_of_two());
    if height < log_message_len {
        return None;
    }
    let width = NativeTerminalWhirLinearizerWeightCols::<F>::width();
    let mut values = F::zero_vec(height * width);
    let mut product = EF::ONE;
    let statement_tidx = verification.batching_challenge_span.end.operations;
    for (coordinate, &point_value) in point.iter().enumerate() {
        let beta_value = beta[log_message_len - 1 - coordinate];
        let factor =
            (EF::ONE - point_value) * (EF::ONE - beta_value.double()) + point_value * beta_value;
        let product_after = product * factor;
        let row = &mut values[coordinate * width..(coordinate + 1) * width];
        let cols: &mut NativeTerminalWhirLinearizerWeightCols<F> = row.borrow_mut();
        cols.active = F::ONE;
        cols.coordinate = F::from_usize(coordinate);
        cols.is_first = F::from_bool(coordinate == 0);
        cols.is_last = F::from_bool(coordinate + 1 == log_message_len);
        cols.statement_tidx = F::from_usize(statement_tidx);
        cols.root = verification.root;
        copy_ext(
            &mut cols.batching_challenge,
            verification.batching_challenge,
        );
        copy_ext(&mut cols.initial_claim, verification.initial_claim);
        copy_ext(&mut cols.beta, beta_value);
        copy_ext(&mut cols.point, point_value);
        copy_ext(&mut cols.factor, factor);
        copy_ext(&mut cols.product_before, product);
        copy_ext(&mut cols.product_after, product_after);
        product = product_after;
    }
    Some(RowMajorMatrix::new(values, width))
}

fn copy_ext(target: &mut [F; D_EF], value: EF) {
    target.copy_from_slice(value.as_basis_coefficients_slice());
}

